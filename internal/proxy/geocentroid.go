// geoCoords 事件坐标：mmdb 经纬度优先，中国回退省份质心，海外回退国家质心
// provinceCoords 兼容 ip2region 的行政区后缀（广东省/北京市/广西壮族自治区/香港特别行政区…）
func provinceCoords(region string) ([2]float64, bool) {
	if region == "" {
		return [2]float64{}, false
	}
	if c, ok := provinceCentroid[region]; ok {
		return c, true
	}
	for _, suf := range []string{"维吾尔自治区", "壮族自治区", "回族自治区", "特别行政区", "自治区", "省", "市"} {
		if t := strings.TrimSuffix(region, suf); t != region {
			if c, ok := provinceCentroid[t]; ok {
				return c, true
			}
		}
	}
	for k, c := range provinceCentroid {
		if strings.HasPrefix(region, k) {
			return c, true
		}
	}
	return [2]float64{}, false
}

func geoCoords(g GeoCity) (float64, float64) {
	if g.Latitude != 0 || g.Longitude != 0 {
		return g.Latitude, g.Longitude
	}
	if g.Country == "CN" || g.Country == "" {
		for _, key := range []string{g.Region, g.City} {
			if c, ok := provinceCoords(key); ok {
				return c[0], c[1]
			}
		}
	}
	if c, ok := countryCentroid[g.Country]; ok {
		return c[0], c[1]
	}
	return 0, 0
}
